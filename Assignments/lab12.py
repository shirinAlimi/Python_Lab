students = ['Shirin', 'Zubaida', 'Ali', 'Zahra', 'Bahara']
print(students)

# append() adds a new student at the end of the list
students.append('Malika')
print(students)

# Insert a student at position 2 (index 1)
students.insert(2, "Nasima")
print(students)

students.remove("Zubaida")
print(students)

students.sort()
print(students)